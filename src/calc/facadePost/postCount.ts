import type { Span } from "../../types/common";

/**
 * Количество стоек фахверка на здание — по практическому правилу
 * (получено от пользователя, не выведено из формул исходных Excel-файлов
 * ИНСИ: там есть только подбор ПРОФИЛЯ стойки, вывод!D41, но не подбор
 * количества — проверено поиском по всем листам обоих файлов
 * 2026-09-04, совпадений с "фах" вне заголовков/подбора профиля нет):
 *
 *   пролёт 9–18м  -> 4 стойки на здание
 *   пролёт 21–24м -> 6 стоек на здание
 *
 * Не зависит от длины здания. Это отдельное правило от шага стоек,
 * который используется только для расчёта нагрузки на одну стойку
 * (см. selectFacadePost) — количество и грузовая ширина здесь
 * намеренно не связаны друг с другом.
 */
export function facadePostCount(span: Span): number {
  return span <= 18 ? 4 : 6;
}
