/**
 * Связи, распорки и фасонки для односкатного «Спринт СП» — «Конструкции
 * из труб», «Уголок», «Лист (фасонки)».
 *
 * ТОЛЬКО для простого случая: один пролёт, два столбца (низкий и
 * высокий), как в singleSlopeFrameGeometry.ts. НЕ для широких/составных
 * пролётов вида «18 (9х9)» — там появляется третья, центральная опора и
 * другие коэффициенты (см. вопрос расчётчику в questions.html).
 *
 * Сверено на ШЕСТИ реальных объектах: «21851» (12×30×7,5), «21777»
 * (12×36×4,5), «21510» (11,6×36×3,6), «22295» (8×24×8), «22271»
 * (8×20×8), «22236» (8,5×50×4). Первая версия этого файла была снята
 * только с «21851» и решила, что коэффициент вертикальных связей — это
 * ручной, необъяснимый выбор расчётчика. Дальнейшая сверка нашла
 * настоящее правило (см. ниже) — коэффициент вертикальных связей
 * оказался ВЫВОДИМЫМ, просто не тем, что предполагала первая версия.
 *
 * ПОДТВЕРЖДЁННАЯ ФОРМУЛА (сходится на всех шести объектах):
 *
 *   Конструкции из труб (т) =
 *       2 × (низкая_высота + 1) × 0,018              стойки, труба 120х5
 *     + 0,0072 × распорок × длина                     распорки, труба 80х3
 *     + 8 × плечо × 0,011                              горизонтальные связи, труба 120х3
 *     + коэфф_верт × плечо × 0,0091                    вертикальные связи, труба 100х3
 *     + ручная добавка
 *     + 0,0096 × периметр обрамления окон              уголок 80х4
 *
 *   плечо = √(катет² + шаг²) × 1,1, катет = пролёт/2 при пролёте ≤ 12 м
 *   (пролёт/4 при пролёте > 12 м — по аналогии с двускатным, см.
 *   bracing.ts, horizBraceRun_m; отдельно на простом случае с пролётом
 *   > 12 м не проверено — широкие пролёты уходят в составную раму, см.
 *   «22134»). Катет один и тот же у горизонтальных и вертикальных
 *   связей — кроме двух объектов с известным отклонением (см. ниже).
 *
 *   коэфф_верт = 8, если низкая_высота ≥ катет (пролёт/2), иначе 4.
 *   Это ЧИСТОЕ правило, не совпадение: подтверждено на всех шести
 *   объектах, включая «22236», где высота (4) и катет (4,25) отличаются
 *   всего на 0,25 м и всё равно попадают на правильную сторону границы.
 *   Инженерный смысл понятен: у высоких узких зданий (высота ≥
 *   половины пролёта) вертикальным связям нужна вдвое большая
 *   металлоёмкость. При коэфф_верт=4 значение совпадает с фиксированным
 *   коэффициентом двускатного каркаса (см. bracing.ts).
 *
 *   Уголок (т) = (рам−2) × 2 × 0,00481 × 1,05 × (пролёт + 3,5)
 *   Лист (т)   = рам × вес_фасонок_на_раму, т
 *
 * ИЗВЕСТНЫЕ ОТКЛОНЕНИЯ (только катет вертикальных связей — коэффициент
 * везде объясняется правилом выше без исключений):
 *   · «21851»: катет вертикальных связей — голое число 4, не пролёт/2
 *     (=6). Похоже на то же самое, что уже встречалось у двускатного
 *     (реальный лист разошёлся с эталонным шаблоном «1ск») — но
 *     подтверждения от расчётчика нет;
 *   · «22236»: катет вертикальных связей — 5, не пролёт/2 (=4,25).
 *   В обоих случаях коэффициент вертикальных связей (правило выше) всё
 *   равно совпал с ведомостью — отклоняется только катет, не коэффициент.
 *
 * ЧТО ОСТАЁТСЯ ПОЛНОСТЬЮ РУЧНЫМ, ПРАВИЛА НЕТ:
 *   · слагаемое-добавка (0,811 в «21851», 2,45 в «21777», 0,368 в
 *     «22295»/«22271», 0,735 в «22236»/«22134» — зависимости от
 *     габаритов не видно);
 *   · количество распорок (2, 3 или 4 в разных объектах);
 *   · труба/уголок на стойки и связи — в «21510» вместо трубы 120х5 на
 *     стойки стоит уголок 120х4, а обе связи — трубой 100х3 (не
 *     120х3+100х3); присутствие строки «Уголок» тоже может быть
 *     отключено (обнулено ×0) для конкретного объекта;
 *   · «вес фасонок на раму» (0,29 т на всех шести объектах — возможно,
 *     не случайно, но своей базы, аналогичной несушкам двускатного, для
 *     односкатного не собирали, поэтому остаётся параметром);
 *   · периметр обрамления окон считается по меньшей мере тремя разными
 *     формулами в разных объектах — вычисляется снаружи и передаётся
 *     готовым числом, этот файл его не выводит.
 *
 * Цены закэшированы в реальных объектах: труба 132 830 ₽/т, уголок
 * 139 150 ₽/т, лист (фасонки) 126 500–132 250 ₽/т — отличаются от
 * констант bracing.ts (136 050 / 172 500 / 137 770), похоже на другую
 * версию прайса «Перекупные», не ошибка; интеграция стоимости в общий
 * расчёт — отдельный шаг, здесь считается только масса.
 */

const TUBE_MASS_t_per_m = {
  "80х3": 0.0072,
  "120х3": 0.011,
  "100х3": 0.0091,
  "120х5": 0.018,
} as const;

export type SingleSlopeTube = keyof typeof TUBE_MASS_t_per_m;

/** Уголок 63х5, т/п.м — то же значение, что и у двускатного (bracing.ts). */
const ANGLE_63X5_t_per_m = 0.00481;
/** Уголок 80х4, т/п.м — обрамление окон, то же значение, что и у двускатного. */
const ANGLE_80X4_t_per_m = 0.0096;

/** Надбавка на раскрой/стыки диагоналей — 1,1, как и у двускатного. */
const BRACE_ALLOWANCE = 1.1;

/** Коэффициент горизонтальных связей — стабилен на всех шести сверенных объектах. */
const HORIZ_BRACE_COEFF = 8;

/**
 * Катет связей — та же граница и та же логика, что у двускатного (см.
 * bracing.ts, horizBraceRun_m). По умолчанию общий для горизонтальных и
 * вертикальных связей (подтверждено на 4 из 6 объектов; «21851» и
 * «22236» — известные отклонения катета вертикальных связей).
 */
function defaultBraceLeg_m(span_m: number): number {
  return span_m <= 12 ? span_m / 2 : span_m / 4;
}

/**
 * Коэффициент вертикальных связей — 8, если низкая высота не меньше
 * катета связей (пролёт/2 при пролёте ≤ 12 м), иначе 4. См. докстринг
 * файла — подтверждено на всех шести сверенных объектах без исключений.
 */
function verticalBraceCoeff(lowHeight_m: number, span_m: number): number {
  return lowHeight_m >= defaultBraceLeg_m(span_m) ? 8 : 4;
}

export interface SingleSlopeBracingInput {
  span_m: number;
  length_m: number;
  /** Высота у низкого карниза (C10 ведомости). */
  lowHeight_m: number;
  /** Шаг рам, м. */
  framePitch_m: number;
  frameCount: number;
  /** Труба стоек — по умолчанию 120х5, как в большинстве сверенных объектов. */
  postsTube?: SingleSlopeTube;
  /** Труба распорок — по умолчанию 80х3, как во всех сверенных объектах. */
  strutTube?: SingleSlopeTube;
  /** «Количество распорок из трубы» — вбито вручную, правила нет (2, 3 или 4 в разных объектах). */
  strutCount: number;
  /** Труба горизонтальных связей — по умолчанию 120х3, как в большинстве сверенных объектов. */
  horizontalBraceTube?: SingleSlopeTube;
  /** Труба вертикальных связей — по умолчанию 100х3, как во всех сверенных объектах. */
  verticalBraceTube?: SingleSlopeTube;
  /** Катет горизонтальных связей, м — по умолчанию пролёт/2 (≤12 м) / пролёт/4 (>12 м). */
  horizontalBraceLeg_m?: number;
  /** Катет вертикальных связей, м — по умолчанию тот же, что у горизонтальных («21851» и «22236» — известные отклонения, см. докстринг). */
  verticalBraceLeg_m?: number;
  /** Слагаемое, вписанное в формулу руками — правила нет, обязательный параметр. */
  extraTubeMass_t: number;
  /** «Металлоемкость узловых пластин», т на раму (0,29 во всех сверенных объектах). */
  gussetMassPerFrame_t: number;
  /** Периметр обрамления оконных проёмов, п.м. */
  windowFramingPerimeter_m?: number;
}

export interface SingleSlopeBracingItem {
  name: string;
  mass_t: number;
  breakdown?: { name: string; mass_t: number }[];
}

export interface SingleSlopeBracingTakeoff {
  items: SingleSlopeBracingItem[];
  totalMass_kg: number;
}

export function computeSingleSlopeBracing(
  input: SingleSlopeBracingInput,
): SingleSlopeBracingTakeoff {
  const postsTube = input.postsTube ?? "120х5";
  const strutTube = input.strutTube ?? "80х3";
  const horizTube = input.horizontalBraceTube ?? "120х3";
  const vertTube = input.verticalBraceTube ?? "100х3";
  const windowPerimeter_m = input.windowFramingPerimeter_m ?? 0;

  const horizLeg_m = input.horizontalBraceLeg_m ?? defaultBraceLeg_m(input.span_m);
  const vertLeg_m = input.verticalBraceLeg_m ?? horizLeg_m;
  const vertCoeff = verticalBraceCoeff(input.lowHeight_m, input.span_m);

  const horizBraceLength_m = Math.hypot(horizLeg_m, input.framePitch_m) * BRACE_ALLOWANCE;
  const vertBraceLength_m = Math.hypot(vertLeg_m, input.framePitch_m) * BRACE_ALLOWANCE;

  const tubeParts = [
    {
      name: `Стойки (труба ${postsTube})`,
      mass_t: 2 * (input.lowHeight_m + 1) * TUBE_MASS_t_per_m[postsTube],
    },
    {
      name: `Распорки (труба ${strutTube})`,
      mass_t: TUBE_MASS_t_per_m[strutTube] * input.strutCount * input.length_m,
    },
    {
      name: `Горизонтальные связи (труба ${horizTube})`,
      mass_t: HORIZ_BRACE_COEFF * horizBraceLength_m * TUBE_MASS_t_per_m[horizTube],
    },
    {
      name: `Вертикальные связи (труба ${vertTube})`,
      mass_t: vertCoeff * vertBraceLength_m * TUBE_MASS_t_per_m[vertTube],
    },
    { name: "Добавка (вручную)", mass_t: input.extraTubeMass_t },
    {
      name: "Обрамление окон (уголок 80х4)",
      mass_t: ANGLE_80X4_t_per_m * windowPerimeter_m,
    },
  ];

  const tubeMass_t = tubeParts.reduce((s, p) => s + p.mass_t, 0);

  const angleMass_t =
    (input.frameCount - 2) * 2 * ANGLE_63X5_t_per_m * 1.05 * (input.span_m + 3.5);

  const plateMass_t = input.frameCount * input.gussetMassPerFrame_t;

  const items: SingleSlopeBracingItem[] = [
    {
      name: "Конструкции из труб",
      mass_t: tubeMass_t,
      breakdown: tubeParts.filter((p) => p.mass_t > 0),
    },
    { name: "Уголок", mass_t: angleMass_t },
    { name: "Лист (фасонки)", mass_t: plateMass_t },
  ];

  return {
    items,
    totalMass_kg: items.reduce((s, i) => s + i.mass_t, 0) * 1000,
  };
}
