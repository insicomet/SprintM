/**
 * Связи, распорки и фасонки для односкатного «Спринт СП» — «Конструкции
 * из труб», «Уголок», «Лист (фасонки)».
 *
 * ТОЛЬКО для простого случая: один пролёт, два столбца (низкий и
 * высокий), как в singleSlopeFrameGeometry.ts. НЕ для широких/составных
 * пролётов вида «18 (9х9)» — там появляется третья, центральная опора и
 * другие коэффициенты (см. вопрос расчётчику в questions.html).
 *
 * ВАЖНАЯ ОГОВОРКА (после сверки на ТРЁХ реальных объектах, не одном):
 * первая версия этого файла была снята с «21851» и совпадала с ним до
 * 10-го знака, но два следующих реальных простых объекта — «21777»
 * (12×36×4,5) и «21510» (11,6×36×3,6) — показали, что часть формулы
 * КАЖДЫЙ РАЗ настраивается расчётчиком вручную под конкретный объект:
 * какая труба идёт на стойки (в «21510» вместо трубы 120х5 — уголок
 * 120х4), какая труба на горизонтальные/вертикальные связи (в «21510» —
 * обе 100х3, а не 120х3+100х3, как в «21851»/«21777»), надбавка на
 * раскрой то 1,1 «зашита» в плечо, то 1,05 снаружи всей скобки, и в
 * «21510» есть третье, отдельное слагаемое (0,4×L156), которого нет в
 * других объектах. Расчётчик КАЖДЫЙ РАЗ пересобирает эту строку под
 * объект, а не применяет одну неизменную формулу — как и с площадью
 * стены (см. singleSlopeFrameGeometry.ts). Что ОСТАЁТСЯ стабильным на
 * всех трёх объектах — оформлено ниже как формула по умолчанию;
 * остальное — обязательные входные параметры без значения по умолчанию,
 * которые обязан задать пользователь.
 *
 * СТАБИЛЬНО (одинаково на всех трёх реальных объектах):
 *   · коэффициент горизонтальных связей = 8;
 *   · плечо горизонтальных связей = пролёт/2 при пролёте ≤ 12 м (пролёт/4
 *     при пролёте > 12 м — по аналогии с двускатным, см. bracing.ts,
 *     horizBraceRun_m; отдельно на простом случае с пролётом > 12 не
 *     проверено — широкие пролёты уходят в составную раму, см. «22134»);
 *   · формула «Уголок» и «Лист» — там же, где эти строки не отключены
 *     вручную (в «21510» «Уголок» намеренно обнулён коэффициентом ×0 —
 *     то есть даже присутствие этой строки в расчёте само по себе
 *     решение расчётчика, не константа).
 *
 * ЛУЧШАЯ ПОДТВЕРЖДЁННАЯ ФОРМУЛА ПО УМОЛЧАНИЮ (чистый случай «21777»,
 * без ручных отклонений, совпадение до 9-го знака):
 *
 *   Конструкции из труб (т) =
 *       2 × (низкая_высота + 1) × 0,018        стойки, труба 120х5
 *     + 0,0072 × распорок × длина               распорки, труба 80х3
 *     + 8 × плечо × 0,011                        горизонтальные связи, труба 120х3
 *     + 4 × плечо × 0,0091                       вертикальные связи, труба 100х3
 *     + ручная добавка
 *     + 0,0096 × периметр обрамления окон        уголок 80х4
 *
 *   плечо = √(катет² + шаг²) × 1,1, катет = пролёт/2 (≤12 м) —
 *   ОДНО И ТО ЖЕ плечо у горизонтальных и вертикальных связей в этом
 *   (чистом) случае. Коэффициент вертикальных связей = 4 — как раз то
 *   же значение, что и у двускатного (см. bracing.ts) — а не 8, как
 *   ошибочно предполагала первая версия этого файла по одному объекту.
 *
 *   Уголок (т) = (рам−2) × 2 × 0,00481 × 1,05 × (пролёт + 3,5)
 *   Лист (т)   = рам × вес_фасонок_на_раму, т
 *
 * ИЗВЕСТНЫЕ ОТКЛОНЕНИЯ ОТ ЭТОЙ ФОРМУЛЫ ПО УМОЛЧАНИЮ (не баг, расчётчик
 * так решил в конкретном файле — оставлены как справка, не как правило):
 *   · «21851» (12×30×7,5): коэффициент вертикальных связей был 8 (не 4),
 *     а катет вертикальных связей — голое число 4, не пролёт/2 (=6).
 *     Похоже на то же самое, что уже встречалось у двускатного (реальный
 *     лист разошёлся с эталонным шаблоном «1ск») — но подтверждения от
 *     расчётчика нет, поэтому это НЕ вошло в формулу по умолчанию;
 *   · «21510» (11,6×36×3,6): стойки — уголок 120х4 (0,01457), а не труба
 *     120х5; горизонтальные И вертикальные связи — обе трубой 100х3, а
 *     не 120х3+100х3; надбавка на раскрой (1,05) применена ко всей
 *     скобке снаружи, а не «зашита» в каждое плечо (1,1); есть третье
 *     отдельное слагаемое (0,4×L156 = 0,4 т), которого нет в других
 *     объектах; «Уголок» в этом файле обнулён (×0).
 *
 * ЧТО ЗАДАЁТСЯ ВРУЧНУЮ И ПРАВИЛА НЕТ (обязательные параметры без
 * умолчания):
 *   · слагаемое-добавка (0,811 в «21851», 2,45 в «21777», 0,735 в
 *     «22134» — зависимости от габаритов не видно);
 *   · количество распорок (4 в «21851»/«21777», 3 в «21510»);
 *   · «вес фасонок на раму» (0,29 т во всех трёх объектах — возможно,
 *     не случайно, но своей базы, аналогичной несушкам двускатного,
 *     для односкатного не собирали, поэтому остаётся параметром).
 *
 * Цены закэшированы в реальных объектах: труба 132 830 ₽/т, уголок
 * 139 150 ₽/т, лист (фасонки) 126 500–132 250 ₽/т — отличаются от
 * констант bracing.ts (136 050 / 172 500 / 137 770), похоже на другую
 * версию прайса «Перекупные», не ошибка; интеграция стоимости в общий
 * расчёт — отдельный шаг, здесь считается только масса.
 */

const TUBE_MASS_t_per_m = {
  "80х3": 0.0072,
  "120х3": 0.011,
  "100х3": 0.0091,
  "120х5": 0.018,
} as const;

export type SingleSlopeTube = keyof typeof TUBE_MASS_t_per_m;

/** Уголок 63х5, т/п.м — то же значение, что и у двускатного (bracing.ts). */
const ANGLE_63X5_t_per_m = 0.00481;
/** Уголок 80х4, т/п.м — обрамление окон, то же значение, что и у двускатного. */
const ANGLE_80X4_t_per_m = 0.0096;

/** Надбавка на раскрой/стыки диагоналей — 1,1, как и у двускатного. */
const BRACE_ALLOWANCE = 1.1;

/** Коэффициент горизонтальных связей — стабилен на всех трёх сверенных объектах. */
const HORIZ_BRACE_COEFF = 8;
/**
 * Коэффициент вертикальных связей по умолчанию — как у двускатного
 * (bracing.ts). Подтверждено на «21777»; «21851» — известное отклонение
 * (см. докстринг файла), для него нужно передать явный override.
 */
const VERT_BRACE_COEFF = 4;

/**
 * Катет связей — та же граница и та же логика, что у двускатного (см.
 * bracing.ts, horizBraceRun_m). По умолчанию общий для горизонтальных и
 * вертикальных связей (подтверждено на «21777»).
 */
function defaultBraceLeg_m(span_m: number): number {
  return span_m <= 12 ? span_m / 2 : span_m / 4;
}

export interface SingleSlopeBracingInput {
  span_m: number;
  length_m: number;
  /** Высота у низкого карниза (C10 ведомости). */
  lowHeight_m: number;
  /** Шаг рам, м. */
  framePitch_m: number;
  frameCount: number;
  /** Труба стоек — по умолчанию 120х5, как в «21851»/«21777». */
  postsTube?: SingleSlopeTube;
  /** Труба распорок — по умолчанию 80х3, как во всех сверенных объектах. */
  strutTube?: SingleSlopeTube;
  /** «Количество распорок из трубы» — вбито вручную, правила нет (4 в «21851»/«21777», 3 в «21510»). */
  strutCount: number;
  /** Труба горизонтальных связей — по умолчанию 120х3, как в «21851»/«21777». */
  horizontalBraceTube?: SingleSlopeTube;
  /** Труба вертикальных связей — по умолчанию 100х3, как во всех сверенных объектах. */
  verticalBraceTube?: SingleSlopeTube;
  /** Катет горизонтальных связей, м — по умолчанию пролёт/2 (≤12 м) / пролёт/4 (>12 м). */
  horizontalBraceLeg_m?: number;
  /** Катет вертикальных связей, м — по умолчанию тот же, что у горизонтальных (подтверждено на «21777»; «21851» — известное отклонение, см. докстринг). */
  verticalBraceLeg_m?: number;
  /** Слагаемое, вписанное в формулу руками — правила нет, обязательный параметр. */
  extraTubeMass_t: number;
  /** «Металлоемкость узловых пластин», т на раму (0,29 во всех сверенных объектах). */
  gussetMassPerFrame_t: number;
  /** Периметр обрамления оконных проёмов, п.м. */
  windowFramingPerimeter_m?: number;
}

export interface SingleSlopeBracingItem {
  name: string;
  mass_t: number;
  breakdown?: { name: string; mass_t: number }[];
}

export interface SingleSlopeBracingTakeoff {
  items: SingleSlopeBracingItem[];
  totalMass_kg: number;
}

export function computeSingleSlopeBracing(
  input: SingleSlopeBracingInput,
): SingleSlopeBracingTakeoff {
  const postsTube = input.postsTube ?? "120х5";
  const strutTube = input.strutTube ?? "80х3";
  const horizTube = input.horizontalBraceTube ?? "120х3";
  const vertTube = input.verticalBraceTube ?? "100х3";
  const windowPerimeter_m = input.windowFramingPerimeter_m ?? 0;

  const horizLeg_m = input.horizontalBraceLeg_m ?? defaultBraceLeg_m(input.span_m);
  const vertLeg_m = input.verticalBraceLeg_m ?? horizLeg_m;

  const horizBraceLength_m = Math.hypot(horizLeg_m, input.framePitch_m) * BRACE_ALLOWANCE;
  const vertBraceLength_m = Math.hypot(vertLeg_m, input.framePitch_m) * BRACE_ALLOWANCE;

  const tubeParts = [
    {
      name: `Стойки (труба ${postsTube})`,
      mass_t: 2 * (input.lowHeight_m + 1) * TUBE_MASS_t_per_m[postsTube],
    },
    {
      name: `Распорки (труба ${strutTube})`,
      mass_t: TUBE_MASS_t_per_m[strutTube] * input.strutCount * input.length_m,
    },
    {
      name: `Горизонтальные связи (труба ${horizTube})`,
      mass_t: HORIZ_BRACE_COEFF * horizBraceLength_m * TUBE_MASS_t_per_m[horizTube],
    },
    {
      name: `Вертикальные связи (труба ${vertTube})`,
      mass_t: VERT_BRACE_COEFF * vertBraceLength_m * TUBE_MASS_t_per_m[vertTube],
    },
    { name: "Добавка (вручную)", mass_t: input.extraTubeMass_t },
    {
      name: "Обрамление окон (уголок 80х4)",
      mass_t: ANGLE_80X4_t_per_m * windowPerimeter_m,
    },
  ];

  const tubeMass_t = tubeParts.reduce((s, p) => s + p.mass_t, 0);

  const angleMass_t =
    (input.frameCount - 2) * 2 * ANGLE_63X5_t_per_m * 1.05 * (input.span_m + 3.5);

  const plateMass_t = input.frameCount * input.gussetMassPerFrame_t;

  const items: SingleSlopeBracingItem[] = [
    {
      name: "Конструкции из труб",
      mass_t: tubeMass_t,
      breakdown: tubeParts.filter((p) => p.mass_t > 0),
    },
    { name: "Уголок", mass_t: angleMass_t },
    { name: "Лист (фасонки)", mass_t: plateMass_t },
  ];

  return {
    items,
    totalMass_kg: items.reduce((s, i) => s + i.mass_t, 0) * 1000,
  };
}
