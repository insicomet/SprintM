import { defaultRoofSlopeDeg } from "../loads/roofLoad";

/**
 * Геометрия рамы «односкатного» ангара («Спринт СП односкат»).
 *
 * ИСПРАВЛЕНО (после проверки на пяти реальных объектах, не одном): первая
 * версия этого файла была снята с листа «1ск» — эталонного примера
 * внутри «21851» — и предполагала уклон, ФИКСИРОВАННЫЙ на 10°, а высоту
 * высокой стойки — выводимой формулой (высота + ригель×sin(10°)). Обе
 * идеи оказались НЕВЕРНЫМИ для реальных объектов:
 *
 *   · РЕАЛЬНЫЙ рабочий лист «18» (не «1ск» — «1ск» это отдельный,
 *     несвязанный образец) считает ригель через угол J14=15° — «=15*3.14/180»
 *     — ТОЧНО ТА ЖЕ формула и то же округление π, что и у ДВУСКАТНОГО
 *     каркаса (frameGeometry.ts, rafterLengthPerFrame_m, SOURCE_PI).
 *     Подтверждено на пяти объектах («21851», «21777», «21510», «22295»,
 *     «22236») — угол 15° везде одинаков, значит односкатный не вводит
 *     свой уклон, а берёт то же правило по пролёту, что и двускатный
 *     (defaultRoofSlopeDeg: 15° при пролёте ≤ 21 м, 6° — больше).
 *     Отдельно на пролёте > 21 м не проверено — широкие пролёты уходят
 *     в составную раму (см. вопрос расчётчику про «22134»).
 *   · Высота высокой стойки в реальном листе — НЕ формула вообще: в
 *     ячейке C22 она вписана вручную голым числом (не ссылкой на
 *     ячейку), и это число даже не всегда БОЛЬШЕ низкой высоты (в
 *     «22295» высокая сторона — 6,2 м при низкой 8 м). Значит расчётчик
 *     смотрит на чертёж и вписывает готовое число, как и с площадью
 *     стены (см. вопрос расчётчику) — выводить эту высоту формулой
 *     нельзя, это входной параметр.
 *
 * ПОДТВЕРЖДЁННЫЕ ФОРМУЛЫ (реальный лист «18», сверено на пяти объектах,
 * совпадение до 9-го знака):
 *
 *   ригель (одна рама) = пролёт / cos(уклон), уклон = defaultRoofSlopeDeg(пролёт)
 *   балка (всего)      = рам × ригель × 2
 *   колонна (всего)    = рам × (низкая_высота × 2 + высокая_высота × 2)
 *
 * НЕ ПРОВЕРЕНО и убрано из этого файла: формула высоты высокой стойки —
 * теперь обязательный входной параметр без значения по умолчанию.
 *
 * Площадь кровли — отдельная, угол-независимая формула, подтверждена на
 * реальном объекте «21851» (396 м² для 12×30) и «22236» (467,5 м² для
 * 8,5×50) без изменений.
 */

/**
 * Значение π, которым исходные ведомости переводят уклон в радианы — то
 * же округление, что и у двускатного (см. frameGeometry.ts, SOURCE_PI).
 */
const SOURCE_PI = 3.14;

function slopeRad(span_m: number): number {
  return (defaultRoofSlopeDeg(span_m) * SOURCE_PI) / 180;
}

/** Длина ригеля одной рамы (одного сплошного ската от карниза до карниза), м. */
export function singleSlopeRafterLength_m(span_m: number): number {
  return span_m / Math.cos(slopeRad(span_m));
}

/** Суммарная длина ригеля (балки) всех рам, п.м. */
export function singleSlopeBeamLength_m(frameCount: number, span_m: number): number {
  return frameCount * singleSlopeRafterLength_m(span_m) * 2;
}

/**
 * Суммарная длина стоек всех рам, п.м. — низкая и высокая стойки.
 * Высокая высота — обязательный параметр (см. докстринг файла: в
 * реальных объектах это вписанное вручную число, не формула).
 */
export function singleSlopeColumnLength_m(
  frameCount: number,
  lowHeight_m: number,
  highHeight_m: number,
): number {
  return frameCount * (lowHeight_m * 2 + highHeight_m * 2);
}

/**
 * Площадь кровли, м² — пролёт × длина × 1,1. Не тригонометрическая
 * поправка на уклон — похоже на отдельный запас на нахлёст/подрезку,
 * взятый как есть из формулы файла, угол-независимая.
 * Подтверждено на «21851» (12×30 → 396) и «22236» (8,5×50 → 467,5).
 */
export function singleSlopeRoofArea_m2(span_m: number, length_m: number): number {
  return span_m * length_m * 1.1;
}
