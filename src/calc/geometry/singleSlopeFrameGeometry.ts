/**
 * Геометрия рамы «односкатного» ангара («Спринт СП односкат») —
 * воспроизведение листа «1ск» реальных ведомостей.
 *
 * Уклон здесь ФИКСИРОВАН на 10° независимо от пролёта — не 15°/6° по
 * порогу 21 м, как у двускатного (см. frameGeometry.ts). Два столбца
 * разной высоты (низкий у карниза с низкой стороны, высокий — с
 * противоположной), один сплошной скат ригеля от низкого до высокого.
 *
 * Подтверждено на «21851» (Бирск, 12×30×7,5): лист «1ск» того же файла
 * (эталонный пример 8×12×3, ТЗ 10256) даёт для этих формул точное
 * совпадение с ведомостью до последнего знака:
 *   J16 (ригель)              = 8,12328619107409  (span/cos(10°))
 *   K16 (высота высокой стойки) = 4,40988600322686 (3 + ригель×sin(10°))
 *   C21 (балка, п.м.)          = 64,98628952859272 (рам × ригель × 2)
 *   C22 (колонна, п.м.)        = 67,27908802581487 (рам × (2×(3+0,5) + 2×(4,40988600322686+0,5)))
 *
 * НЕ ПРОВЕРЕНО: формула площади стены (в реальном "рабочем" листе
 * объекта, не в эталоне «1ск», числа рассчитаны вручную с округлением
 * высот и вычетом проёмов — не сводится к чистой формуле по двум
 * файлам подряд, см. вопрос расчётчику). Площадь кровли — сходится
 * (см. singleSlopeRoofArea_m2).
 */

/** Уклон односкатной кровли, град — фиксирован, не зависит от пролёта. */
export const SINGLE_SLOPE_DEG = 10;

/**
 * Значение π, которым исходные ведомости переводят уклон в радианы
 * (см. frameGeometry.ts — тот же приём, то же округление автора файла).
 */
const SOURCE_PI = 3.14;

function slopeRad(): number {
  return (SINGLE_SLOPE_DEG * SOURCE_PI) / 180;
}

/** Длина ригеля (одного сплошного ската от карниза до карниза), м — пролёт/cos(уклон). */
export function singleSlopeRafterLength_m(span_m: number): number {
  return span_m / Math.cos(slopeRad());
}

/**
 * Высота высокой стойки, м — высота у низкого карниза плюс подъём ската
 * (длина ригеля × sin(уклон)).
 */
export function singleSlopeHighColumnHeight_m(lowHeight_m: number, span_m: number): number {
  return lowHeight_m + singleSlopeRafterLength_m(span_m) * Math.sin(slopeRad());
}

/** Суммарная длина ригеля (балки) всех рам, п.м. — та же формула, что у двускатного (frameCount × ригель × 2). */
export function singleSlopeBeamLength_m(frameCount: number, span_m: number): number {
  return frameCount * singleSlopeRafterLength_m(span_m) * 2;
}

/**
 * Суммарная длина стоек всех рам, п.м. — низкая и высокая стойки, у
 * каждой свой запас +0,5 м (не совпадает с EAVE_OFFSET_M=0,07 у
 * двускатного — другая, отдельная константа для этого типа рамы).
 */
export function singleSlopeColumnLength_m(
  frameCount: number,
  lowHeight_m: number,
  highHeight_m: number,
): number {
  return frameCount * (2 * (lowHeight_m + 0.5) + 2 * (highHeight_m + 0.5));
}

/**
 * Площадь кровли, м² — пролёт × длина × 1,1. Не тригонометрическая
 * поправка на уклон (та дала бы ×1,015 при 10°) — похоже на отдельный
 * запас на нахлёст/подрезку, взятый как есть из формулы файла.
 * Подтверждено на «21851»: 12×30×1,1 = 396 — точное совпадение с
 * реальной ведомостью (строка «СП 200», 396 м²).
 */
export function singleSlopeRoofArea_m2(span_m: number, length_m: number): number {
  return span_m * length_m * 1.1;
}
