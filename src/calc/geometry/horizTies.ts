import rawHorizTies from "../../data/horizTies.json";
import type { Span } from "../../types/common";

interface RawHorizTiesRow {
  span: number;
  svCode: string;
  kPerM: number;
  constKg: number;
}

const table = rawHorizTies as RawHorizTiesRow[];

/**
 * Масса горизонтальных связей/распорок на здание, кг.
 *
 * ИСТОЧНИК: столбец "S" ("металлоемкость гориз. связей, распорок, кг")
 * из файла-калькулятора ИНСИ (листы "9м"/"12м"/"15м"/"18м"/"21м"), формула
 * вида "=AA{row}*23,76+910" — линейна по длине здания (AA), с константой,
 * зависящей от пролёта и кода "с/в" (на практике совпадает по шагу рам).
 * Проверено на всех 5 пролётах (9/12/15/18/21м), константа воспроизведена
 * с точностью до 0,01 кг для каждой строки исходной таблицы.
 *
 * ОТКРЫТЫЙ ВОПРОС: в исходном файле эта таблица заполнена только для
 * высотной корзины 3,6м — данных по 4,8м/6,0м нет. Физически горизонтальные
 * связи (в плоскости кровли) не должны зависеть от высоты колонн, поэтому
 * здесь применяется одна и та же таблица для всех высотных корзин пролёта.
 * Не проверено на реальном примере с высотой ≠ 3,6м.
 *
 * Пролёт 24м не включён — исходная таблица для него имеет другую структуру
 * столбцов (см. отдельный TODO при появлении данных).
 */
export function computeHorizTiesMass_kg(span: Span, svCode: string, buildingLength_m: number): number | null {
  const row = table.find((r) => r.span === span && r.svCode === svCode);
  if (!row) return null;
  return buildingLength_m * row.kPerM + row.constKg;
}
