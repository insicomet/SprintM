import type { BuildingGeometry } from "./types";

/**
 * Площадь кровли для раскладки панелей, м² — по формуле обеих реальных
 * ведомостей (строка "СП 150"): пятно застройки с надбавкой 3%.
 *
 *   пролёт × длина × 1,03
 *
 * То есть ИНСИ не считает истинную площадь по скату, а берёт проекцию с
 * коэффициентом: при уклоне 15° точный множитель 1/cos = 1,0353, они
 * округляют до 1,03. Для 18×30 это 556,2 м² против геометрических
 * 559,0 м². Проёмы (фонари, вентиляция) не вычитаются.
 */
export function computeRoofArea_m2(geometry: BuildingGeometry): number {
  return geometry.span_m * geometry.length_m * ROOF_AREA_SLOPE_ALLOWANCE;
}

/** Надбавка на уклон в площади кровли — 1,03 в обеих исходных ведомостях. */
const ROOF_AREA_SLOPE_ALLOWANCE = 1.03;

/**
 * Площадь стен, м² — по формуле ведомостей (строка "СП"):
 *
 *   (пролёт + длина) × 2 × высота  +  надбавка на фронтоны
 *
 * Первое слагаемое — периметр на высоту (оба продольных фасада плюс
 * прямоугольная часть обоих торцов). Второе — надбавка на фронтоны:
 * ИНСИ считает её не по геометрии треугольника, а как пролёт × 2 на
 * оба фронтона, и при пролёте БОЛЬШЕ 12 м удваивает ещё раз — «на запас
 * под подрезку панелей» (ответ расчётчика). Для 18 м это 72 м² против
 * геометрических 43,4 м².
 *
 * В "22285" (18 м) надбавка записана без этого удвоения, 36 м² вместо
 * 72; расчётчик подтвердила, что это ошибка в файле. Пролёт РОВНО 12 м
 * (в "21923", Москва) в файле тоже не удвоен — но это не та же ошибка:
 * расчётчик уточнила границу отдельно и прямо: «Граница больше 12,
 * начиная с 13, при пролёте 12м умножать не нужно». То есть порог —
 * строгое неравенство, 12 м в категорию удвоения не попадает.
 */
export function computeWallArea_m2(geometry: BuildingGeometry): number {
  const perimeterWalls = (geometry.span_m + geometry.length_m) * 2 * geometry.height_m;
  return perimeterWalls + gableAllowance_m2(geometry.span_m);
}

/** Пролёт, после которого (не включая) надбавка на фронтоны удваивается «на запас». */
const GABLE_DOUBLING_SPAN_M = 12;

/** Надбавка на фронтоны, м²: пролёт × 2, а больше 12 м — ещё раз × 2. */
export function gableAllowance_m2(span_m: number): number {
  return span_m * 2 * (span_m > GABLE_DOUBLING_SPAN_M ? 2 : 1);
}

/**
 * Площадь стен под профлист, м² (брутто, без вычета проёмов) — по формуле
 * из самого файла ведомости (строка "С-18", лист "12м" — «22326»/«21942»
 * и другие СП-проекты), но там она умножена на 0: расчётчик считает эти
 * здания по СП, а строка профлиста в шаблоне остаётся выключенной.
 *
 *   (пролёт + длина) × 2 × (высота + 0,5) + пролёт × 2, всё × 1,1
 *
 * Тот же вид, что и у СП (computeWallArea_m2), но с постоянной надбавкой
 * на фронтоны (пролёт × 2, без удвоения выше 12 м) и запасом 1,1 вместо
 * 1,05 — видимо, у профлиста больше нахлёст/обрезки. ВАЖНО: формула взята
 * из выключенной строки — ни на одном реальном профлистовом объекте
 * (ненулевой) не сверялась. Требует подтверждения на первом же реальном
 * расчёте профлистового склада.
 */
export function computeProfnastilWallGrossArea_m2(geometry: BuildingGeometry): number {
  return (
    ((geometry.span_m + geometry.length_m) * 2 * (geometry.height_m + 0.5) + geometry.span_m * 2) *
    1.1
  );
}

/**
 * Площадь кровли под профлист, м² — та же ведомость, строка "С-44"
 * (лист "12м"), тоже выключена (×0) в СП-проектах:
 *
 *   (пролёт + 0,6) × (длина + 1) × 1,1
 *
 * Другая надбавка на свесы, чем у СП (computeRoofArea_m2, ×1,03) —
 * профлист выступает за периметр каркаса иначе. Как и со стеной, формула
 * из выключенной строки — не сверена ни на одном реальном объекте.
 */
export function computeProfnastilRoofArea_m2(geometry: BuildingGeometry): number {
  return (geometry.span_m + 0.6) * (geometry.length_m + 1) * 1.1;
}
