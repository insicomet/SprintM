/**
 * Кровельные расходники для односкатного «Спринт СП» — простой случай
 * (один пролёт, два столбца), см. singleSlopeFrameGeometry.ts.
 *
 * Сверено на ЧЕТЫРЁХ реальных объектах: «21851» (12×30×7,5), «21777»
 * (12×36×4,5), «22295» (8×24×8), «22236» (8,5×50×4).
 *
 * ЧИСТЫЕ ФОРМУЛЫ (совпадают на всех четырёх объектах без исключений):
 *
 *   ГВЛ + на рамы, м²    = 2,5 × (пролёт + 0,5 + 2×низкая_высота) × рам
 *   Саморез 3,5х25, шт    = 30 × (ГВЛ + на рамы)
 *   Фанера, м²            = 9 × длина
 *   ИзоспанВ, м²          = пролёт × длина × 1,25
 *   Изоспан АМ, м²        = пролёт × длина × 1,25 (та же формула, отдельная строка)
 *   Воронки вн. вод, шт   = 15 (одно и то же число на всех четырёх объектах,
 *                                от габаритов не зависит — похоже на
 *                                типовой набор, а не расчёт по площади)
 *
 * НЕ ВОШЛО (нет выводимого правила, обязательные параметры без
 * умолчания):
 *   · «лист пл оц 1мм» (обшивка коньковых/торцевых узлов) — формула
 *     2×count×длина×1,1, но count вбит вручную (5, 6, 8, 12, 19 в
 *     разных объектах) без видимой связи с габаритами;
 *   · «Линотерм» — своя формула на каждый объект (в «21851» одна форма,
 *     в остальных трёх — другая, проще), тоже с ручным счётчиком;
 *   · «Шнур упл» (уплотнительный шнур) — формула ссылается на плечо,
 *     которое считается через угол 15° (а не 10°, как у самой рамы) —
 *     похоже на оставшийся кусок ДВУСКАТНОГО шаблона (лист «18» несёт
 *     оба типа расчёта), не пересчитанный при копировании под
 *     односкатный; не стал переносить эту, вероятно ошибочную, формулу.
 *   · «Саморез 4,8x20» и «Утеплитель» (первые две строки раздела) — в
 *     обоих сверенных случаях равны 0 (ссылаются на C77/C78/E14, не
 *     относящиеся к этому типу конструктива) — не включены.
 *
 * Накладные расходы (2%) здесь не начисляются — как и в bracing.ts, они
 * идут на раздел целиком в исходнике.
 */

export interface SingleSlopeRoofEnvelopeItem {
  name: string;
  quantity: number;
  unit: string;
}

export interface SingleSlopeRoofEnvelopeInput {
  span_m: number;
  length_m: number;
  /** Высота у низкого карниза. */
  lowHeight_m: number;
  frameCount: number;
}

export function computeSingleSlopeRoofEnvelope(
  input: SingleSlopeRoofEnvelopeInput,
): SingleSlopeRoofEnvelopeItem[] {
  const { span_m, length_m, lowHeight_m, frameCount } = input;

  const gklPlusFrames_m2 = 2.5 * (span_m + 0.5 + 2 * lowHeight_m) * frameCount;
  const vaporBarrier_m2 = span_m * length_m * 1.25;

  return [
    { name: "ГВЛ + на рамы", quantity: gklPlusFrames_m2, unit: "м²" },
    { name: "Саморез 3,5х25", quantity: 30 * gklPlusFrames_m2, unit: "шт." },
    { name: "Фанера", quantity: 9 * length_m, unit: "м²" },
    { name: "ИзоспанВ", quantity: vaporBarrier_m2, unit: "м²" },
    { name: "Изоспан АМ", quantity: vaporBarrier_m2, unit: "м²" },
    { name: "Воронки вн. вод", quantity: 15, unit: "шт." },
  ];
}
